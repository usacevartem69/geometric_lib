def area(a, h): 
    '''
    Возаращает площадь треугольника с основанием a и высотой h

        Параметры:
                a(int/float): десятичное вещественное число
                h(int/float): десятичное вещественное чсило
        
        Возвращаемое значение:
                area(int/float, int/float): десятичное вещественное число

        Пример:
                area(3,4) = 3 * 4 / 2 = 6
    '''
    return a * h / 2 

def perimeter(a, b, c): 
    '''
    Возаращает периметр треугольника со сторонами a, b, c.

        Параметры:
                a(int/float): десятичное вещественное число
                b(int/float): десятичное вещественное число
                c(int/float): десятичное вещественное число
        
        Возвращаемое значение:
                perimeter(int/float,int/float, int/float): десятичное вещественное число

        Пример:
                perimeter(3, 4, 5) = 3 + 4 + 5 = 12
    '''
    return a + b + c 
